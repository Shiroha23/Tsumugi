/// 由 WHATWG Encoding Standard 的索引文件生成 `lib/core/encoding/whatwg_indexes.dart`。
///
/// 用法（索引文件需先手动下载到同一目录：`encodings.json` 与各 `index-*.txt`，
/// 见 https://encoding.spec.whatwg.org/#indexes）：
///
/// ```
/// dart run tool/encoding/gen_whatwg_indexes.dart <索引目录>
/// dart format lib/core/encoding/whatwg_indexes.dart
/// ```
///
/// 多字节索引按「码点差值 → zigzag varint → zlib → base64」压缩，运行时首次使用时解压。
library;

import 'dart:convert';
import 'dart:io';

/// 支持的多字节编码及其索引（GBK 与 gb18030 共用 gb18030 解码器）。
const _multiByte = {
  'gb18030': 'gb18030',
  'big5': 'big5',
  'jis0208': 'jis0208',
  'euc-kr': 'euc-kr',
};

/// encodings.json 中的名称 → 本项目的规范名（小写）。不在此表也不是单字节编码的不支持。
const _supported = {
  'utf-8': 'utf-8',
  'utf-16le': 'utf-16le',
  'utf-16be': 'utf-16be',
  'gbk': 'gb18030',
  'gb18030': 'gb18030',
  'big5': 'big5',
  'shift_jis': 'shift_jis',
  'euc-kr': 'euc-kr',
  'x-user-defined': 'x-user-defined',
};

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'usage: dart run tool/encoding/gen_whatwg_indexes.dart <dir>',
    );
    exit(64);
  }
  final dir = Directory(args.single);
  final groups = jsonDecode(
    File('${dir.path}/encodings.json').readAsStringSync(),
  ) as List<Object?>;

  final labels = <String, String>{};
  final singleByte = <String>[];
  for (final g in groups.cast<Map<String, Object?>>()) {
    final isSingle = g['heading'] == 'Legacy single-byte encodings';
    for (final e in (g['encodings']! as List).cast<Map<String, Object?>>()) {
      final name = (e['name']! as String).toLowerCase();
      final canonical = isSingle ? name : _supported[name];
      if (canonical == null) continue;
      if (isSingle) singleByte.add(name);
      for (final l in (e['labels']! as List).cast<String>()) {
        labels[l] = canonical;
      }
    }
  }

  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/encoding/gen_whatwg_indexes.dart — do not edit.',
    )
    ..writeln('//')
    ..writeln('// Data derived from the WHATWG Encoding Standard')
    ..writeln('// (https://encoding.spec.whatwg.org/), Copyright © WHATWG')
    ..writeln(
      '// (Apple, Google, Mozilla, Microsoft). Portions incorporated into',
    )
    ..writeln('// source code are licensed under the BSD 3-Clause License.')
    ..writeln('//')
    ..writeln('// Index identifiers:');
  final sources = {
    for (final n in _multiByte.values) 'index-$n.txt',
    'index-gb18030-ranges.txt',
    for (final n in singleByte) 'index-${_indexName(n)}.txt',
  };
  for (final s in sources) {
    final id = File('${dir.path}/$s')
        .readAsLinesSync()
        .firstWhere((l) => l.startsWith('# Identifier:'))
        .substring('# Identifier: '.length);
    out.writeln('//   $s $id');
  }
  out
    ..writeln()
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('/// WHATWG 标签（小写）→ 规范名。只含已实现解码器的编码。')
    ..writeln('const whatwgLabels = <String, String>{');
  for (final e in labels.entries) {
    out.writeln("  '${e.key}': '${e.value}',");
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('/// 单字节编码：0x80–0xFF 对应的 128 个码点（U+FFFD 表示未定义）。')
    ..writeln('const singleByteTables = <String, String>{');
  for (final n in singleByte) {
    final m = _readIndex(dir, _indexName(n));
    final sb = StringBuffer();
    for (var i = 0; i < 128; i++) {
      sb.write('\\u{${(m[i] ?? 0xFFFD).toRadixString(16).toUpperCase()}}');
    }
    out.writeln("  '$n': '$sb',");
  }
  out.writeln('};');

  for (final MapEntry(key: varName, value: file) in _multiByte.entries) {
    final m = _readIndex(dir, file);
    final length = m.keys.reduce((a, b) => a > b ? a : b) + 1;
    final bytes = <int>[];
    var prev = 0;
    for (var i = 0; i < length; i++) {
      final v = m[i] ?? 0;
      final d = v - prev;
      prev = v;
      var z = d >= 0 ? d << 1 : ((-d) << 1) - 1;
      while (true) {
        final b = z & 0x7F;
        z >>= 7;
        if (z == 0) {
          bytes.add(b);
          break;
        }
        bytes.add(b | 0x80);
      }
    }
    final b64 = base64.encode(ZLibEncoder(level: 9).convert(bytes));
    final id = _camel(varName);
    out
      ..writeln()
      ..writeln('/// index-$file.txt：指针 0..${length - 1}，0 表示无映射。')
      ..writeln('const ${id}IndexLength = $length;')
      ..writeln()
      ..writeln('const ${id}IndexData =');
    for (var i = 0; i < b64.length; i += 76) {
      final end = i + 76 < b64.length ? i + 76 : b64.length;
      out.writeln(
        "    '${b64.substring(i, end)}'${end == b64.length ? ';' : ''}",
      );
    }
  }

  final ranges = File('${dir.path}/index-gb18030-ranges.txt')
      .readAsLinesSync()
      .where((l) => l.trim().isNotEmpty && !l.startsWith('#'))
      .map((l) => l.trim().split(RegExp(r'\s+')))
      .expand((p) => [int.parse(p[0]), int.parse(p[1].substring(2), radix: 16)])
      .toList();
  out
    ..writeln()
    ..writeln('/// index-gb18030-ranges.txt：成对的（指针偏移, 码点），按指针升序。')
    ..writeln('const gb18030Ranges = <int>[${ranges.join(', ')}];');

  File('lib/core/encoding/whatwg_indexes.dart').writeAsStringSync('$out');
  stdout.writeln('wrote lib/core/encoding/whatwg_indexes.dart');
}

/// iso-8859-8-i 与 iso-8859-8 共用索引。
String _indexName(String encoding) =>
    encoding == 'iso-8859-8-i' ? 'iso-8859-8' : encoding;

Map<int, int> _readIndex(Directory dir, String name) => {
  for (final l in File('${dir.path}/index-$name.txt').readAsLinesSync())
    if (l.trim().isNotEmpty && !l.startsWith('#'))
      int.parse(l.trim().split(RegExp(r'\s+'))[0]): int.parse(
        l.trim().split(RegExp(r'\s+'))[1].substring(2),
        radix: 16,
      ),
};

String _camel(String s) => s
    .split(RegExp('[-_]'))
    .indexed
    .map(
      (e) => e.$1 == 0 ? e.$2 : '${e.$2[0].toUpperCase()}${e.$2.substring(1)}',
    )
    .join();
